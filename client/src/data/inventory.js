export function getInventoryBySite(siteId) {
  return inventory.filter((i) => i.siteId === siteId)
}

export function getInventoryById(invId) {
  return inventory.find((i) => i.id === invId)
}

export function daysRemaining(item) {
  if (!item.consumptionPerDay) return Infinity
  return Math.round((item.quantity / item.consumptionPerDay) * 10) / 10
}
