/**
 * Translate an English string into Hindi using exact dictionary & pattern replacements
 */
export function translateToHindi(text) {
  if (!text || typeof text !== 'string') return text
  const trimmed = text.trim()
  if (!trimmed) return text

  // 1. Direct exact dictionary match
  if (HINDI_DICTIONARY[trimmed]) {
    return text.replace(trimmed, HINDI_DICTIONARY[trimmed])
  }

  // 2. Case-insensitive dictionary search
  for (const [en, hi] of Object.entries(HINDI_DICTIONARY)) {
    if (trimmed.toLowerCase() === en.toLowerCase()) {
      return text.replace(trimmed, hi)
    }
  }

  // 3. Keyword/Pattern substitutions
  let translated = text
  for (const [pattern, hi] of KEYWORD_REPLACEMENTS) {
    translated = translated.replace(pattern, hi)
  }

  return translated
}

/**
 * Recursively translate all text nodes inside a DOM element
 */
export function translateDOMElement(rootNode, targetLang) {
  if (!rootNode || !rootNode.nodeType) return

  const isHindi = targetLang === 'hi'

  const walker = document.createTreeWalker(
    rootNode,
    NodeFilter.SHOW_TEXT,
    {
      acceptNode(node) {
        // Skip script, style, textarea, input values, and code blocks
        const parent = node.parentElement
        if (!parent) return NodeFilter.FILTER_REJECT
        const tag = parent.tagName.toLowerCase()
        if (tag === 'script' || tag === 'style' || tag === 'code' || tag === 'noscript') {
          return NodeFilter.FILTER_REJECT
        }
        if (parent.closest('[data-no-translate]')) {
          return NodeFilter.FILTER_REJECT
        }
        return NodeFilter.FILTER_ACCEPT
      },
    }
  )

  let currentNode = walker.nextNode()
  while (currentNode) {
    const original = currentNode._originalText || currentNode.nodeValue

    if (!currentNode._originalText) {
      currentNode._originalText = original
    }

    if (isHindi) {
      currentNode.nodeValue = translateToHindi(original)
    } else {
      currentNode.nodeValue = currentNode._originalText
    }

    currentNode = walker.nextNode()
  }

  // Translate common attributes: placeholder, title
  const elementsWithAttr = rootNode.querySelectorAll?.('input[placeholder], textarea[placeholder], button[title], a[title]') || []
  elementsWithAttr.forEach((el) => {
    if (el.placeholder) {
      if (!el.dataset.origPlaceholder) {
        el.dataset.origPlaceholder = el.placeholder
      }
      el.placeholder = isHindi ? translateToHindi(el.dataset.origPlaceholder) : el.dataset.origPlaceholder
    }
    if (el.title) {
      if (!el.dataset.origTitle) {
        el.dataset.origTitle = el.title
      }
      el.title = isHindi ? translateToHindi(el.dataset.origTitle) : el.dataset.origTitle
    }
  })
}
